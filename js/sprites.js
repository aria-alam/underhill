// Render an 8x8 sprite onto a canvas context at (x, y) scaled by factor
function drawSprite(ctx, sprite, x, y, scale) {
    for (let row = 0; row < sprite.length; row++) {
        for (let col = 0; col < sprite[row].length; col++) {
            const colorIdx = sprite[row][col];
            if (colorIdx === 0) continue; // transparent
            ctx.fillStyle = PALETTE[colorIdx];
            ctx.fillRect(
                x + col * scale,
                y + row * scale,
                scale,
                scale
            );
        }
    }
}

// Render sprite with a color replacement (used for NPC suit recoloring)
function drawSpriteRecolor(ctx, sprite, x, y, scale, fromColorIdx, toColor) {
    for (let row = 0; row < sprite.length; row++) {
        for (let col = 0; col < sprite[row].length; col++) {
            const colorIdx = sprite[row][col];
            if (colorIdx === 0) continue;
            ctx.fillStyle = (colorIdx === fromColorIdx) ? toColor : PALETTE[colorIdx];
            ctx.fillRect(
                x + col * scale,
                y + row * scale,
                scale,
                scale
            );
        }
    }
}
